#!/bin/bash
# Builds the הסמסטרון menu bar app + widget, without an Xcode project (needs Xcode installed).
#   ./mac/build.sh            build into mac/build/
#   ./mac/build.sh install    build, copy to /Applications and start it
# The first run asks for the calendar address from the web app (⚙️ → 📆 יומן → העתק); it
# only tells the app where your sync gist is, and is kept in mac/gist.local (not committed).
set -euo pipefail
cd "$(dirname "$0")"

NAME=Hasemestron
BUNDLE_ID=io.github.akivamprager.semestron
APP_URL=https://akivamprager.github.io/semester-tracker/
MIN_OS=14.0
OUT=${BUILD_DIR:-build}

# ---- where the data is ----
if [ ! -s gist.local ]; then
  read -r -p "כתובת היומן מהאפליקציה (⚙️ → 📆 יומן → העתק): " url
  echo "$url" > gist.local
fi
URL=$(cat gist.local)
if [[ ! "$URL" =~ gist\.githubusercontent\.com/([^/]+)/([0-9a-f]+) ]]; then
  echo "זו לא כתובת גיסט: $URL — מחק את mac/gist.local ונסה שוב." >&2
  exit 1
fi
GIST_USER=${BASH_REMATCH[1]}
GIST_ID=${BASH_REMATCH[2]}

# ---- toolchain ----
DEV=${DEVELOPER_DIR:-$(xcode-select -p 2>/dev/null || echo /Applications/Xcode.app/Contents/Developer)}
SWIFTC=$DEV/Toolchains/XcodeDefault.xctoolchain/usr/bin/swiftc
SDK=$DEV/Platforms/MacOSX.platform/Developer/SDKs/MacOSX.sdk
TARGET=$(uname -m)-apple-macos$MIN_OS
[ -x "$SWIFTC" ] || { echo "Xcode not found ($DEV) — install Xcode from the App Store." >&2; exit 1; }
CACHE=${TMPDIR:-/tmp}/hasemestron-modcache
SWIFT_FLAGS=(-sdk "$SDK" -target "$TARGET" -parse-as-library -O -module-cache-path "$CACHE")
# extra compiler flags, e.g. SWIFT_EXTRA="-disable-sandbox" when building inside another sandbox
read -r -a EXTRA <<< "${SWIFT_EXTRA:-}"
SWIFT_FLAGS+=(${EXTRA[@]+"${EXTRA[@]}"})

rm -rf "$OUT"
APP=$OUT/$NAME.app
EXT=$APP/Contents/PlugIns/${NAME}Widget.appex
mkdir -p "$APP/Contents/MacOS" "$APP/Contents/Resources" "$EXT/Contents/MacOS"

cat > "$OUT/Config.swift" <<EOF
// generated by build.sh
enum Config {
    static let gistID = "$GIST_ID"
    static let rawBase = "https://gist.githubusercontent.com/$GIST_USER/$GIST_ID/raw/"
    static let appURL = "$APP_URL"
}
EOF

echo "▸ compiling the app"
"$SWIFTC" "${SWIFT_FLAGS[@]}" -module-name $NAME \
  Sources/Shared/*.swift Sources/App/*.swift "$OUT/Config.swift" -o "$APP/Contents/MacOS/$NAME"

echo "▸ compiling the widget"
"$SWIFTC" "${SWIFT_FLAGS[@]}" -application-extension -module-name ${NAME}Widget \
  Sources/Shared/*.swift Sources/Widget/*.swift "$OUT/Config.swift" -o "$EXT/Contents/MacOS/${NAME}Widget"

VERSION=$(date +%Y.%m.%d)
BUILD=$(date +%s)

cat > "$APP/Contents/Info.plist" <<EOF
<?xml version="1.0" encoding="UTF-8"?>
<!DOCTYPE plist PUBLIC "-//Apple//DTD PLIST 1.0//EN" "http://www.apple.com/DTDs/PropertyList-1.0.dtd">
<plist version="1.0"><dict>
  <key>CFBundleIdentifier</key><string>$BUNDLE_ID</string>
  <key>CFBundleName</key><string>הסמסטרון</string>
  <key>CFBundleDisplayName</key><string>הסמסטרון</string>
  <key>CFBundleExecutable</key><string>$NAME</string>
  <key>CFBundlePackageType</key><string>APPL</string>
  <key>CFBundleShortVersionString</key><string>$VERSION</string>
  <key>CFBundleVersion</key><string>$BUILD</string>
  <key>CFBundleIconFile</key><string>AppIcon</string>
  <key>CFBundleDevelopmentRegion</key><string>he</string>
  <key>LSMinimumSystemVersion</key><string>$MIN_OS</string>
  <key>LSUIElement</key><true/>
  <key>NSHighResolutionCapable</key><true/>
</dict></plist>
EOF

cat > "$EXT/Contents/Info.plist" <<EOF
<?xml version="1.0" encoding="UTF-8"?>
<!DOCTYPE plist PUBLIC "-//Apple//DTD PLIST 1.0//EN" "http://www.apple.com/DTDs/PropertyList-1.0.dtd">
<plist version="1.0"><dict>
  <key>CFBundleIdentifier</key><string>$BUNDLE_ID.widget</string>
  <key>CFBundleName</key><string>הסמסטרון</string>
  <key>CFBundleDisplayName</key><string>הסמסטרון</string>
  <key>CFBundleExecutable</key><string>${NAME}Widget</string>
  <key>CFBundlePackageType</key><string>XPC!</string>
  <key>CFBundleShortVersionString</key><string>$VERSION</string>
  <key>CFBundleVersion</key><string>$BUILD</string>
  <key>CFBundleDevelopmentRegion</key><string>he</string>
  <key>LSMinimumSystemVersion</key><string>$MIN_OS</string>
  <key>NSExtension</key><dict>
    <key>NSExtensionPointIdentifier</key><string>com.apple.widgetkit-extension</string>
  </dict>
</dict></plist>
EOF

# Widgets must run sandboxed; this one only needs to download widget.json.
cat > "$OUT/widget.entitlements" <<EOF
<?xml version="1.0" encoding="UTF-8"?>
<!DOCTYPE plist PUBLIC "-//Apple//DTD PLIST 1.0//EN" "http://www.apple.com/DTDs/PropertyList-1.0.dtd">
<plist version="1.0"><dict>
  <key>com.apple.security.app-sandbox</key><true/>
  <key>com.apple.security.network.client</key><true/>
</dict></plist>
EOF

cp AppIcon.icns "$APP/Contents/Resources/AppIcon.icns" # made by tools/make-icons.mjs

echo "▸ signing (local, no Apple account needed)"
codesign --force --sign - --entitlements "$OUT/widget.entitlements" "$EXT"
codesign --force --sign - "$APP"

echo "✓ built $APP"

if [ "${1:-}" = install ]; then
  pkill -x $NAME 2>/dev/null || true
  rm -rf "/Applications/$NAME.app"
  cp -R "$APP" /Applications/
  # register the widget with the system, then start the menu bar app
  /System/Library/Frameworks/CoreServices.framework/Frameworks/LaunchServices.framework/Support/lsregister -f "/Applications/$NAME.app" || true
  open "/Applications/$NAME.app"
  echo "✓ installed in /Applications and started — look for 🎓 next to the clock."
fi
